// ---- Turns the Tiled map's ART layers into a data file the game can draw from ----
// The game's collision data (js/data/collision.js) came out of the Tiled map; the art did not, it was only
// available as one flattened picture (assets/images/background.png). A picture of ONE map can't be repeated
// to match collision that repeats at a different spacing, so the art is exported the same way the collision
// was: as tile data. Run `npm run export-art` after editing assets/tiled/verticalPlatformer.tmx in Tiled.
//
// Reads:  assets/tiled/verticalPlatformer.tmx
// Writes: js/data/art.js   (artLayers, artScenery, ART_TILE_COLUMNS)

const fs = require('node:fs')
const path = require('node:path')

const TMX_PATH = path.join(__dirname, '..', 'assets', 'tiled', 'verticalPlatformer.tmx')
const OUT_PATH = path.join(__dirname, '..', 'js', 'data', 'art.js')

// Which Tiled layer becomes which entry of artLayers
const LAYERS = {
    trees: 'Trees',                    //Trees, the dark ground and the left ledge: scenery at the bottom of the map
    foreground: 'Foreground Objects',  //Bushes on the ground (drawn at 39% opacity in the map)
    lights: 'Lights',                  //The vines and glowing stars hanging under the platforms
    platforms: 'Platforms',            //The platform planks themselves
}
const SCENERY_IMAGES = {199: 'background_0', 200: 'background_1', 201: 'background_2'} //Tiled tile-object ids -> image names

/** @returns {Object} Tile layers by name: {width, height, ids: number[]} (ids are row by row, 0 = empty) */
function parseLayers(tmx) {
    const layers = {}
    for (const match of tmx.matchAll(/<layer id="\d+" name="([^"]+)" width="(\d+)" height="(\d+)"[^>]*>\s*<data encoding="csv">(.*?)<\/data>/gs)) {
        layers[match[1]] = {width: +match[2], height: +match[3], ids: match[4].match(/\d+/g).map(Number)}
    }
    return layers
}

/**
 * The scenery images placed on the map as Tiled "tile objects". Tiled anchors a tile object by its BOTTOM
 * left corner, so the top is y - height.
 * @returns {{image: string, x: number, y: number, width: number, height: number}[]} In drawing order
 */
function parseScenery(tmx) {
    return [...tmx.matchAll(/<object id="\d+" gid="(\d+)" x="([-\d.]+)" y="([-\d.]+)" width="([-\d.]+)" height="([-\d.]+)"\/>/g)].map(match => ({
        image: SCENERY_IMAGES[match[1]],
        x: +match[2],
        y: +(+match[3] - +match[5]).toFixed(3),
        width: +match[4],
        height: +match[5],
    }))
}

/** @returns {String} The full text of js/data/art.js for the given Tiled map */
function buildArtSource(tmx) {
    const layers = parseLayers(tmx)
    const scenery = parseScenery(tmx)
    const rows = (ids, width) => {
        const lines = []
        for (let i = 0; i < ids.length; i += width) lines.push('        ' + ids.slice(i, i + width).join(','))
        return lines.join(',\n')
    }
    const body = Object.entries(LAYERS).map(([key, name]) => {
        const layer = layers[name]
        if (!layer) throw new Error(`The Tiled map has no layer called "${name}"`)
        return `    // ${name}\n    ${key}: [\n${rows(layer.ids, layer.width)}\n    ],`
    }).join('\n')
    return `// GENERATED by tools/export-art.js from assets/tiled/verticalPlatformer.tmx. Do not edit by hand:
// change the map in Tiled, then run \`npm run export-art\` (a test fails if this file is out of date).
//
// artLayers: the map's art layers as tile ids, 36 per row, 27 rows. 0 = empty; otherwise the id counts
// from 1 across the tileset image, row by row (see ART_TILE_COLUMNS).
const ART_TILE_COLUMNS = 18 //Tiles per row in assets/tiled/assets/tileset.png

const artLayers = {
${body}
}

// artScenery: the sky and cloud images behind everything, in drawing order (x, y = top left corner, in map pixels)
const artScenery = ${JSON.stringify(scenery, null, 4)}
`
}

module.exports = {parseLayers, parseScenery, buildArtSource, TMX_PATH, OUT_PATH}

if (require.main === module) {
    fs.writeFileSync(OUT_PATH, buildArtSource(fs.readFileSync(TMX_PATH, 'utf8')))
    console.log(`Wrote ${path.relative(process.cwd(), OUT_PATH)}`)
}
